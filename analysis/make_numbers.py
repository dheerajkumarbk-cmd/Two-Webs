"""Write report/numbers.tex: every number in the report as a LaTeX macro,
generated from docs/data.json so the text cannot drift from the data."""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = json.load(open(os.path.join(ROOT, "docs", "data.json"), encoding="utf-8"))
M = []


def put(name, value):
    M.append("\\newcommand{\\%s}{%s}" % (name, value))


def pct(x, d=1):
    return ("%%.%df" % d) % (100.0 * x) + "\\%"


def num(n):
    return "{:,}".format(n).replace(",", "{,}")


def rate(prefix, m):
    put(prefix + "K", num(m["k"]))
    put(prefix + "N", num(m["n"]))
    put(prefix + "P", pct(m["rate"]) if m["rate"] is not None else "n/a")
    put(prefix + "CI", "%.1f--%.1f\\%%" % (100 * m["low"], 100 * m["high"]) if m["rate"] is not None else "n/a")


for tag, ident in (("Ctl", "browser-control"), ("Ua", "Claude-User"), ("Acc", "browser-md"), ("Both", "Claude-User-md")):
    t = D["triggers"][ident]
    put(tag + "Sites", num(t["sites_comparable"]))
    rate(tag + "Differ", t["sites_differ"])
    rate(tag + "Flag", t["sites_flagged"])
    rate(tag + "Twin", t["sites_markdown"])
put("VennAccept", D["venn"]["accept"])
put("VennMissed", D["venn"]["accept_missed_by_user_agent"])
put("VennUa", D["venn"]["user_agent"])
s = [x for x in D["sensitivity"] if x["min_facts"] == 3][0]
put("TwN", s["twins"])
put("TwFacts", num(s["facts"]))
put("TwLost", num(int(round(s["pooled_loss"] * s["facts"]))))
put("TwPooled", pct(s["pooled_loss"]))
put("TwBoot", "%.1f--%.1f\\%%" % (100 * s["boot_low"], 100 * s["boot_high"]))
put("TwMedian", pct(s["median_site_loss"]))
rate("TwNone", s["lose_none"])
rate("TwHalf", s["lose_half"])
lo = min(x["pooled_loss"] for x in D["sensitivity"])
hi = max(x["pooled_loss"] for x in D["sensitivity"])
put("SensRange", "%.1f--%.1f\\%%" % (100 * lo, 100 * hi))
for m in D["by_type"]:
    rate("Type" + m["type"].capitalize(), m)
c = D["control"]
put("CtlPages", num(c["pages"]))
put("CtlFacts", num(c["facts"]))
put("CtlFactsLost", num(c["facts_lost"]))
put("CtlFactsP", pct(c["facts_lost"] / float(c["facts"]), 2))
put("CtlPagesFlagged", c["pages_flagged"])
rb = D["rank_buckets"]
put("RankRange", "%.1f--%.1f\\%%" % (100 * min(x["rate"] for x in rb), 100 * max(x["rate"] for x in rb)))
put("NRequests", num(D["counts"]["requests"]))
put("NPages", num(D["counts"]["pages"]))
put("NSitesLoaded", num(D["counts"]["sites"]))
put("TrigLoaded", num(D["samples"]["trigger"]["sites_loaded"]))
g = D["samples"]["general"]
put("GenLoaded", num(g["sites_loaded"]))
put("GenComparable", num(g["sites_comparable"]))
rate("GenFlag", g["divergent_auto"])
with open(os.path.join(ROOT, "report", "numbers.tex"), "w", encoding="utf-8") as f:
    f.write("% Generated by analysis/make_numbers.py. Do not edit by hand.\n" + "\n".join(M) + "\n")
print(len(M), "macros written")
